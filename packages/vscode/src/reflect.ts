export const REFLECT_TASK_BOOK = `反思

对当前目录的记忆库做一次反思：补整理的漏网，把一个主题的碎片聚成
综述。作为后台任务跑，不与用户闲聊——本消息即任务书全文，无参数、
无主题，选题是你自己的第一步（见「第一步」末段）。素材不足（三库
search --all 命中 < 3 条且记忆无增量）→ 报告「主题太薄」直接收工，
不硬写综述。

全程只有两种操作：读（bash，不动文件）和最后一轮写（统一落盘）。
「加工」不是独立操作——它是读完之后你在上下文里做的综合，最终以
写命令的形态落盘。上下文易失：读段中断零成本、整轮重跑即可，
写段中断留下半成品状态——所以写集中在最后，写后自查发现的错误
在本轮订正，不留给用户收拾。

## 分身定位

你带着 fork 时刻的全部记忆（live 行 + 摘要）。记忆是主通道，检索是
辅助：记忆里已有的不当新发现；记忆覆盖不到的远期才翻 turns/归档。
哪些前提变了、哪些挂账后来做了——记忆有一手感知。

## 执行纪律（两个读段通用）

- 先探体积再读：一切批量输出与要读的正文文件（list/search 结果、
  要 cat 的 md）先 wc -c，超 12k 分段读（sed -n '1,40p'）或 grep
  过滤——bash 输出 16k 截断砍中间，残缺清单比不扫更危险。
- 读正文一律 bash 直读（sed -n '1,50p' .simple-code/notes/<name>.md），
  不走 "$SIMPLE_CODE_NOTE" read——批量 read 会把 lastRead 刷成同一
  时刻、霸榜常驻索引；bash cat 不更新心跳。
- 不碰 skill、代码、配置文件——发现问题只写进报告。
- 不删任何文件；过时只走 superseded。
- 不做评价类总结（「本周很有效率」一概不要）。

## 第一步：轻扫读（目的：点出整理候选 + 定主题）

三库 list --all（必须 --all：默认收起超半年未用，反思不能被过滤
骗到）。对照用三信号流读、一遍过不回头：名字认识且记忆说前提没了
→ 过期候选；名字认识且记忆说后续做了 → 闭环候选；名字不认识（远
期暗区，fork 记忆只剩摘要）→ 跳过——轻扫不求全，硬判是浪费。逐库
点候选：

- note：记忆里知道前提消失的（版本已发、架构已改、结论被实测推翻）
  → superseded 候选。不合并不删除。
- event：「说好的下一步后来做了」→ progress 闭环候选。同战役碎片 →
  merge 候选，证据必须命令级可查，任一：① 两条正文互相印证 + 时间
  相邻；② 旧条 lastRead/updated 距新条 created 跨过 180 天线 + 主题
  同一；③ 同一产物（同批 commit、同一文件）。名字像不是证据；
  周期性复发是同一战役的 progress——先想闭环，再想合并。
- lesson：只捡明显漏网的（日常纪律「失败 ≥2 次当场 write」覆盖增量）。
- 打捞：记忆里最近的拍板、notes 无对应条目的 → 新 note 候选；条目
  在但缺新拍板内容的 → 更新候选（活文档补内容，不是 superseded）。

挂账检测：分身记忆对照为主（fork 时带着记忆，「说好的事做没做」
有一手感知）；远期到记忆只剩摘要的，grep 复合词（待补/待定/待验
证/待用户/挂账——裸「待」全是「等待」级噪声）做候选，记忆裁决
——只当候选生成器，不当判据。

定主题（轻扫结果 + fork 时刻记忆——fork 时继承的是当时全部记忆，
和主会话一样新）：取碎片量最大的簇——已有综述或定稿 note 盖着的
战役不算碎片；同分不出先后就选最近的战役。
选题与理由写进报告开头——治理需要知道这次反思的是什么。

## 第二步：主题读（目的：聚齐素材，在上下文里做综合）

围绕第一步选定的主题读全素材：

1. 列全碎片清单：三库 search --all（关键词一个串：单词直接传、
   多词引号包成一串；不吞 stderr）+ 记忆里已知的——漏素材的综述
   有盲区。search 命中与第一步清单对不齐是警报：先核对调用形态，
   别把残缺结果当全集。
2. 逐条 bash 直读正文。
3. 边读边在上下文里综合：碎片怎么咬合、边界在哪、什么改动会碰什么；
   疑似矛盾（时间先后、被推翻没标、碎片主张与记忆不符）只标记、
   不裁决——读段无从裁决，降级为候选，进第三步拿第三方证据
   （turns/runlog/git）命令级求证。综合只存在于上下文，写入前
   中断即丢、整轮重跑。

第二步收口（进入第三步前必做）：对照本次工具调用与返回结果，列出
实际执行的主题 search --all 命令及命中清单，以及每条作为依据的素材
读到的范围（全文/首尾/未读）。list --all 只给索引行，不能代替主题 search --all；
没执行的现在执行，命中里没看过的逐条判断是否相关；作为依据却只读
首尾或被截断的补读全文。补不齐的从依据里剔除、写进报告「未核实」，
不报「素材已齐」。这一项没过不进第三步。

## 第三步：写入（唯一写阶段）

写入前由你自己对照本次工具调用与返回结果自查，不凭「应该做过」：
- 第二步收口是否已完成；继承记忆与本次核实分清，仍不足的缩小结论
  或放弃。
- 拿准备写入的结论逐项对照来源原文，不是只重读自己的总结：数字及
  加总、时间、版本、commit 是否一致；「已完成/已发布/已验证」是否
  有对应证据；来源矛盾是否已求证，未解的不能写成定论。

第一、二步攒下的全部写动作在这里统一执行（与主会话 agent 同权，
无审批）。每条执行前先求证，证据分三档：命令级（git/sqlite/grep
实测）直接落；外部世界动作（发布/上传类）本地无痕的，以 memory
search 定位 turn 作据、在 progress 行注明证据形态；「没再复现」
不是复验。闭环与更新候选落笔前先读目标正文核挂账——索引描述
滞后是常态，轻扫的 flag 只是嫌疑。证据不足的放弃并记录原因，
不降格写入。写入顺序：先碎片（progress/补正文），后综述，最后
收尾 event——综述要引的碎片得先落。

- note：新结论直接 write；已有条目缺新结论的用 patch 补正文（活文档
  更新）；superseded 用 patch 在头部加 status:、by:。纯末尾追加
  apply_patch 匹配脆弱，cat >> 前备份到 .simple-code/tmp/、追加后
  diff 校验。
- event：闭环 progress <name> "<一句话>"；碎片 merge（旧文件先
  cp 到 .simple-code/tmp/event-merge-backup-$(date +%s)/，events
  通常不入 git，删了没有退路）；遗漏的事件补录。
- lesson："$SIMPLE_CODE_LESSON" write（五段格式）。

综述（主题加工的产物）规格：

- 新 note，name 用主题（如 review-缓存），头部「素材截至
  YYYY-MM-DD」+ 素材 name 清单。
- 每句综合都能在碎片里找到出处，不添加碎片里没有的推断。
- 组织分三段：时间线、现状、开口。开口=该主题还欠的事，是综述
  盖住后下轮重选它的唯一理由——无新开口的主题不再选。
- 综述不替代碎片、不进任何碎片的 by: 链。同主题第二次综述撞名拒绝，
  天然防重写。
- lesson 碎片指向同一根因的 → 综述里单列「教训共性」一节，不新建
  lesson。
- 跨战役模式（同型事 ≥2 次且做法趋同）→ 新 skill 候选，只写进报告
  ——skill 是用户指令区，反思只提案不建。

## 第四步：自查与订正（必做）

由本任务自己完成，不另起核验任务。写完后用 bash 重新读实际修改或
新建的文件，必要时对照 diff 与来源原文，不能只看工具返回「成功」：
- 改动是否落在正确位置，新旧结论是否仍冲突，是否引入了无来源推断。
- 综述素材清单是否与实际阅读一致；开口只列尚欠的事，教训共性不算
  待办；报告中的文件、条数、完成状态是否与实际落盘一致。
发现错误当场订正，再复读改动处；不能确认的明确写「未核实」，不把
部分完成报成全部完成。收尾 event 写完也复读。

## 收尾（必做）

1. 报告：写了什么（每条一句理由）、闭环了什么、放弃了什么及原因。
   简述自查发现并订正了什么、还有什么未核实；不要只写「自查通过」。
2. 归档本次反思为 event：name 用 memory-reflect-<主题> 前缀（如
   memory-reflect-recall-review——产品按此前缀显示「上次反思」）。
   event-bin 无 create 子命令，用 apply_patch 直写
   .simple-code/events/<name>.md，front matter 与进展段格式照抄
   现有 event 文件。created/updated 先执行 date '+%Y-%m-%d %H:%M:%S'，
   照抄输出，不手填、不估。
3. 报告交给用户过目——用户可当场订正，这就是治理。`
